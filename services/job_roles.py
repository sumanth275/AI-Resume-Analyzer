def get_job_roles():
    """Return all available predefined job roles."""
    return JOB_ROLES


def get_job_description(role_name):
    """Return the job description for a selected role."""
    role = JOB_ROLES.get(role_name)

    if role:
        return role["description"].strip()

    return ""


def get_role_skills(role_name):
    """Return core and supporting skills for a job role."""

    role = JOB_ROLES.get(role_name)

    if not role:
        return {
            "core_skills": [],
            "supporting_skills": []
        }

    return {
        "core_skills": role.get("core_skills", []),
        "supporting_skills": role.get("supporting_skills", [])
    }